import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'frontend', 'dist');

function injectEarlyHints() {
  const indexPath = path.join(distDir, 'index.html');
  const headersPath = path.join(distDir, '_headers');

  if (!fs.existsSync(indexPath)) {
    console.warn('index.html not found, skipping early hints injection.');
    return;
  }

  const html = fs.readFileSync(indexPath, 'utf-8');
  // Match the main client CSS generated by Vinxi/SolidStart
  // Usually looks like: <link href="/_build/assets/client-Dc9PPs5A.css" rel="stylesheet" ... />
  const cssMatch = html.match(/<link[^>]*href="(\/_build\/assets\/[^"]+\.css)"[^>]*rel="stylesheet"[^>]*>/);

  if (!cssMatch) {
    console.warn('Could not find main CSS file in index.html, skipping early hints injection.');
    return;
  }

  const cssPath = cssMatch[1];
  console.log(`Found main CSS: ${cssPath}`);

  let headers = '';
  if (fs.existsSync(headersPath)) {
    headers = fs.readFileSync(headersPath, 'utf-8');
  }

  // Preload rule for Early Hints
  const earlyHintRule = `  Link: <${cssPath}>; rel=preload; as=style\n`;

  // Apply to all pre-rendered static routes
  const routes = ['/', '/about', '/licenses', '/404'];
  
  let newHeaders = headers;
  // Ensure a newline before appending
  if (newHeaders && !newHeaders.endsWith('\n')) {
    newHeaders += '\n';
  }

  for (const route of routes) {
    newHeaders += `\n${route}\n${earlyHintRule}`;
  }

  fs.writeFileSync(headersPath, newHeaders);
  console.log('Successfully injected 103 Early Hints into _headers');
}

injectEarlyHints();
